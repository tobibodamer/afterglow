import json
SB = r'E:\experimentswithclaude\random\afterglow\sandbox\piano'
L = json.load(open(SB + r'\layout_b.json'))
PL = json.load(open(SB + r'\plate_b.json'))
r3 = lambda v: round(float(v), 4)
strings = []
for k, s in zip(L['keys'], L['strings']):
    n = s['n']
    strings.append({
        'n': n, 'note': s['name'], 'midi': k['midi'], 'key_color': k['color'], 'key_x_center': r3(k['x_center']),
        'strings': s['nstr'], 'wound': s['wound'], 'wire_d_mm': s['d_mm'], 'speaking_length': r3(s['L']),
        'strike_from_front_termination': r3(s['xH']), 'angle_deg_from_z_toward_x': s['theta'],
        'strike_xz': [r3(v) for v in s['strike']], 'front_termination_xz': [r3(v) for v in s['front']],
        'bridge_xz': [r3(v) for v in s['bridge']], 'hitch_xz': [r3(v) for v in s['hitch']], 'tuning_pin_rowA_xz': [r3(v) for v in s['pin']],
        'front_termination': 'agraffe' if n <= 52 else 'capo_bar', 'damper': n <= 67,
        'front_red_braid': n <= 76, 'rear_red_felt': n <= 45,
    })
out = {
    '_about': 'Afterglow piano B-class (211 cm) layout. Metres. Origin on floor below front-left corner of case; x right (bass->treble), z away from player, y up. Generated by sandbox/piano/gen_layout.py + gen_plate.py; see research/piano.md for derivation and sources.',
    'case_outline_xz': [[r3(a), r3(b)] for a, b in L['outline']],
    'rim_thickness': 0.060,
    'belly_rail_line_xz': PL['belly'],
    'plate': {
        'outline_polygons_xz': [[[r3(a), r3(b)] for a, b in poly] for poly in PL['plate']],
        'interior_rings_xz': [[[r3(a), r3(b)] for a, b in ring] for ring in PL['plate_interiors']],
        'struts': PL['struts'], 'holes_xz': PL['holes'], 'bolts_xz': PL['bolts'],
        'front_plate_back_edge_xz': [[r3(a), r3(b)] for a, b in PL['front_plate_back_edge']],
    },
    'bass_bridge_xz': [[r3(a), r3(b)] for a, b in PL['bass_bridge']],
    'long_bridge_xz': [[r3(a), r3(b)] for a, b in PL['long_bridge']],
    'hammer_x': {k: v for k, v in L['hammer_x'].items()},
    'notes': strings,
}
json.dump(out, open(r'E:\experimentswithclaude\random\afterglow\research\piano_b_layout.json', 'w'), indent=1)
print('written', len(strings))
